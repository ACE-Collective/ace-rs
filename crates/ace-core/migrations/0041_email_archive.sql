-- The email archive (PLAN.md 7.5 batch 9): ace3's `email-archive` database, which its
-- `email_archiver` module writes and its `message_id_analyzer_v2`, `url_email_pivot_analyzer` and
-- `email` API router read. Each archived email is an object in the bucket's `email_archive` pool,
-- gzipped and encrypted with ACE's key in the core (`ace_core::email_archive`), held until its rows
-- go; these tables find it by its hash, its Message-ID and the URLs below it.
--
-- As in ace3, `archive`, `archive_index` and `email_history` are range-partitioned by `insert_date`,
-- a partition an ISO week (`pYYYYwWW`) with a default partition, `p_catchall`, under them, and a whole
-- week goes at once when its rows are past retention (`ace3/docs/DATABASE_PARTITIONS.md`). The
-- scheduler's `email_archive_partitions` task makes the weeks ahead and drops the old ones, as
-- ace3's `ace partitions maintain`. ace3's `archive_server` isn't carried over: one bucket holds
-- every node's archive, so an archive has no server.
CREATE SCHEMA email_archive;

CREATE SEQUENCE email_archive.archive_id_seq;

CREATE TABLE email_archive.archive (
    archive_id bigint NOT NULL DEFAULT nextval('email_archive.archive_id_seq'),
    -- The SHA-256 of the email's bytes, ace3's `hash`.
    hash bytea NOT NULL CHECK (length(hash) = 32),
    -- The encrypted object in the `email_archive` pool, by the SHA-256 of its own bytes.
    object_sha256 text NOT NULL,
    -- UTC, to the second, as ace3 truncates it: it's part of the unique key.
    insert_date timestamp(0) NOT NULL,
    -- The file the archiver archived, whose URLs are indexed once its root's analysis is done.
    root_id uuid NOT NULL,
    observable_id bigint NOT NULL,
    PRIMARY KEY (archive_id, insert_date),
    UNIQUE (hash, insert_date)
) PARTITION BY RANGE (insert_date);

CREATE INDEX archive_by_insert_date ON email_archive.archive (insert_date);
CREATE INDEX archive_by_root ON email_archive.archive (root_id);
CREATE INDEX archive_by_hash ON email_archive.archive (hash);

ALTER SEQUENCE email_archive.archive_id_seq OWNED BY email_archive.archive.archive_id;

-- What an archived email is found by: its normalized Message-ID and each URL below it, by the
-- SHA-256 of the value, as ace3's `UNHEX(SHA2(value, 256))`. ace3's enum has seven more fields it no
-- longer writes; the check holds the two it does.
CREATE TABLE email_archive.archive_index (
    field text NOT NULL CHECK (field IN ('message_id', 'url')),
    hash bytea NOT NULL CHECK (length(hash) = 32),
    archive_id bigint NOT NULL,
    -- The archive's own `insert_date`, so an email's index goes with it.
    insert_date timestamp(0) NOT NULL,
    PRIMARY KEY (hash, archive_id, field, insert_date)
) PARTITION BY RANGE (insert_date);

CREATE INDEX archive_index_by_archive ON email_archive.archive_index (archive_id);
CREATE INDEX archive_index_by_field_hash ON email_archive.archive_index (field, hash);

-- Who received each archived email: its normalized Message-ID and each normalized envelope
-- recipient, with their hashes, as ace3's.
CREATE TABLE email_archive.email_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    insert_date timestamp(0) NOT NULL,
    message_id text NOT NULL,
    message_id_hash bytea NOT NULL CHECK (length(message_id_hash) = 32),
    recipient text NOT NULL,
    recipient_hash bytea NOT NULL CHECK (length(recipient_hash) = 32),
    PRIMARY KEY (id, insert_date),
    UNIQUE (message_id_hash, recipient_hash, insert_date)
) PARTITION BY RANGE (insert_date);

CREATE INDEX email_history_by_insert_date ON email_archive.email_history (insert_date);
CREATE INDEX email_history_by_message_id ON email_archive.email_history (message_id_hash);
CREATE INDEX email_history_by_recipient ON email_archive.email_history (recipient_hash);

-- The default partitions. Maintenance makes each week's partition before rows reach it, and never
-- splits a week out of a catchall that holds rows of that week (ace3's rule: a catchall must stay
-- empty).
CREATE TABLE email_archive.archive_p_catchall PARTITION OF email_archive.archive DEFAULT;
CREATE TABLE email_archive.archive_index_p_catchall PARTITION OF email_archive.archive_index DEFAULT;
CREATE TABLE email_archive.email_history_p_catchall PARTITION OF email_archive.email_history DEFAULT;

-- The scheduler's task acts as a component of its own (PLAN.md 5.2, 6.7), holding only this. ace3's
-- `ace partitions maintain` runs from cron with the database's credentials, under no permission.
