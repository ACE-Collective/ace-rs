# Helpers the table generators share. Each generator is run as
#   cat tables/common.py tables/NAME.py | docker exec -i ace-dev-1 /venv/bin/python3 - > src/tables/NAME.rs
# (tables/run does all of them), so this file is pasted in front of the generator, not imported.

import sys
import unicodedata

assert sys.version_info[:3] == (3, 14, 10), sys.version
assert unicodedata.unidata_version == "16.0.0"

ALL = range(0x110000)


def is_surrogate(cp):
    return 0xD800 <= cp <= 0xDFFF


def rust_str(s):
    out = []
    for c in s:
        o = ord(c)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif 0x20 <= o < 0x7F:
            out.append(c)
        else:
            out.append("\\u{%x}" % o)
    return '"' + "".join(out) + '"'


def header(what):
    print("// @generated by crates/ace-pycompat/tables/%s from Python %s, unicodedata %s." % (
        what, sys.version.split()[0], unicodedata.unidata_version))
    print("// Regenerate with crates/ace-pycompat/tables/run; don't edit.")
    print()


def ranges(pred):
    """Inclusive (start, end) runs of the code points where pred holds, surrogates included."""
    out = []
    start = None
    for cp in ALL:
        ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit_ranges(name, rs, doc):
    print("/// %s" % doc)
    print("#[rustfmt::skip]")
    print("pub(crate) static %s: &[(u32, u32)] = &[" % name)
    line = []
    for a, b in rs:
        line.append("(0x%x, 0x%x)," % (a, b))
        if len(line) == 6:
            print("    " + " ".join(line))
            line = []
    if line:
        print("    " + " ".join(line))
    print("];")
    print()


def value_runs(f):
    """(start, value) at each change of f over all code points; surrogates included."""
    out = []
    prev = object()
    for cp in ALL:
        v = f(cp)
        if v != prev:
            out.append((cp, v))
            prev = v
    return out
